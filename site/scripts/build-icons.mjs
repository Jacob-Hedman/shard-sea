// Writes src/lib/icons.ts: the Tabler outline icons the site uses, inlined as SVG paths so
// no icon font or CDN is needed (the D&D 3.5 Codex's approach). Needs `@tabler/icons`
// (npm i --no-save @tabler/icons); add a name to NAMES and re-run.
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = [
  'search', 'chevron-down', 'chevron-right', 'arrow-up', 'arrow-right', 'arrow-left', 'alert-triangle',
  'info-circle', 'help-circle', 'flame', 'plus', 'book', 'book-2', 'x', 'world', 'wand', 'user-star',
  'user-plus', 'user-heart', 'triangle-inverted', 'trending-up', 'tools', 'tags', 'sword', 'star',
  'sparkles', 'ship', 'shield', 'school', 'refresh', 'pick', 'package', 'mood-sick', 'menu-2', 'mask',
  'map-2', 'link', 'layout-grid', 'id-badge', 'hourglass', 'home', 'ghost-2', 'flask', 'flag',
  'file-text', 'file', 'droplet-filled', 'droplet', 'dice', 'diamond', 'database', 'crystal-ball', 'cpu',
  'chart-radar', 'category-2', 'building-castle', 'building-arch', 'brand-github', 'brain', 'bolt',
  'activity-heartbeat', 'versions', 'skull', 'armor', 'history', 'users', 'external-link',
];
const out = {};
for (const n of NAMES) {
  let svg;
  try { svg = readFileSync(`node_modules/@tabler/icons/icons/outline/${n}.svg`, 'utf8'); }
  catch { try { svg = readFileSync(`node_modules/@tabler/icons/icons/filled/${n.replace(/-filled$/, '')}.svg`, 'utf8'); } catch { console.warn('missing', n); continue; } }
  out[n] = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]).filter((d) => d !== 'M0 0h24v24H0z');
}
writeFileSync('src/lib/icons.ts', `// Tabler Icons (MIT, https://tabler.io/icons), outline set: only the icons the site uses, inlined
// as SVG paths so no icon font or CDN is needed. Generated by scripts/build-icons.mjs.
export const ICONS: Record<string, string[]> = ${JSON.stringify(out, null, 2)};
`);
console.log(Object.keys(out).length, 'icons');
